export const I18n = {
  get lang() { return lang; },
  set lang(v) {
    lang = v === "en" ? "en" : "zh";
    if (typeof document !== "undefined") document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
  },
  t(key, vars) {
    let s = dict[lang][key];
    if (s === undefined) s = dict.zh[key];
    if (s === undefined) return key;
    if (vars) {
      return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k])));
    }
    return s;
  },
  /** Fill every element carrying data-i18n. */
  apply(root = document) {
    for (const el of root.querySelectorAll("[data-i18n]")) {
      const key = el.getAttribute("data-i18n");
      const text = this.t(key);
      if (el.tagName === "INPUT") el.placeholder = text;
      else el.textContent = text;
    }
  },
};

export const t = (k, v) => I18n.t(k, v);
